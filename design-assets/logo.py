def svg(size, bg=True):
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 108 108">']
    if bg: out.append(f'<rect width="108" height="108" fill="{PAPER}"/><circle cx="54" cy="54" r="33" fill="none" stroke="#ddd" stroke-width="0.3"/>')
    out.append('<g transform="translate(54 54) scale(0.93) translate(-53 -58)">')
    for d, f, s, w in S:
        out.append(f'<path d="{d}" fill="{f or "none"}"' + (f' stroke="{s}" stroke-width="{w}" stroke-linecap="round" stroke-linejoin="round"' if s else '') + '/>')
    return "\n".join(out + ["</g></svg>"])
def vector(name):
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- The builder at a fork in the trail, unsure of the way. Generated by design-assets/logo.py. -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">']
    out.append('    <group android:pivotX="54" android:pivotY="54" android:scaleX="0.93" android:scaleY="0.93" android:translateX="1" android:translateY="-4">')
    for d, f, s, w in S:
        a = [f'android:pathData="{d}"']
        if f: a.append(f'android:fillColor="{f}"')
        if s: a += [f'android:strokeColor="{s}"', f'android:strokeWidth="{w}"', 'android:strokeLineCap="round"', 'android:strokeLineJoin="round"']
        out.append("    <path " + "\n        ".join(a) + " />")
    return "\n".join(out + ["    </group>", "</vector>"]) + "\n"
